    private void jBtnPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnPesquisarActionPerformed


        String pesquisa = jTxtF.getText().trim();

        if (pesquisa.isEmpty()) {
            carregarProfissionais();
            return;
        }

        javax.swing.table.DefaultTableModel modelo =
                (javax.swing.table.DefaultTableModel)
                JTbAnaliseProfissionais.getModel();

        boolean encontrado = false;

        for (int i = 0; i < modelo.getRowCount(); i++) {

            String nome = modelo.getValueAt(i, 1).toString();

            if (nome.toLowerCase().contains(pesquisa.toLowerCase())) {
                JTbAnaliseProfissionais.setRowSelectionInterval(i, i);
                JTbAnaliseProfissionais.scrollRectToVisible(
                        JTbAnaliseProfissionais.getCellRect(i, 0, true)
                );

                encontrado = true;
                break;
            }
        }

        if (!encontrado) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Profissional não encontrado."
            );
        }

    }//GEN-LAST:event_jBtnPesquisarActionPerformed

