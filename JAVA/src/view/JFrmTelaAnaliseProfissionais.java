    private void jBtnReprovarprofissionalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnReprovarprofissionalActionPerformed
        //linhaSelecionada -> variavel pra selecionar a linha  //getSelectedRow--> método pra indentificar a linha selecionada
        //lembrando que no java comeca por 0 a contagem entao se selecionamos a linha 3 aparece 2 (0,1,2)
        int linhaSelecionada = JTbAnaliseProfissionais.getSelectedRow();

    if (linhaSelecionada == -1) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Selecione um profissional para reprovar."
        );
        return;
    }

    int idUsuario = Integer.parseInt(
            JTbAnaliseProfissionais.getValueAt(linhaSelecionada, 0).toString()
    );

    int confirmacao = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente reprovar este profissional?",
            "Confirmar reprovação",
            javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (confirmacao != javax.swing.JOptionPane.YES_OPTION) {
        return;
    }

    String sql = "UPDATE profissional " +
            "SET status_cadastro = 'REPROVADO' " +
            "WHERE id_usuario = ? " +
            "AND status_cadastro = 'PENDENTE'";

    try (java.sql.Connection conn = Conexao.abrirConexao();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setInt(1, idUsuario);

        int linhasAlteradas = stmt.executeUpdate();

        if (linhasAlteradas > 0) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Profissional reprovado com sucesso!"
            );

            carregarProfissionais();

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Não foi possível reprovar o profissional."
            );
        }

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Erro ao reprovar profissional: " + e.getMessage()
        );
    }
    }//GEN-LAST:event_jBtnReprovarprofissionalActionPerformed

