    // metodo que vai carregar os profissionais 
    private void carregarProfissionais() {

    String sql = "SELECT " +
        "u.id_usuario, u.nome, u.email, p.status_cadastro, " +
        "p.whatsapp, p.descricao, p.cidade, p.data_cadastro, " +
        "p.rg_frente, p.rg_verso " + //JLAB FOTOS CONSULTA NO SQL 
        "FROM usuario u " +
        "INNER JOIN profissional p " +
        "ON u.id_usuario = p.id_usuario " +
        "WHERE u.tipo_usuario = 'profissional' " +
        "AND p.status_cadastro = 'PENDENTE'";
    
/* pegando os dados da classe conexao onde as informações 
    vem do banco passam por ela e vem até aqui pra mostrar os profissionais*/ 
    try (java.sql.Connection conn =
           Conexao.abrirConexao();
         java.sql.PreparedStatement stmt = conn.prepareStatement(sql);
         java.sql.ResultSet rs = stmt.executeQuery()) {

        javax.swing.table.DefaultTableModel modelo =
                (javax.swing.table.DefaultTableModel)
                JTbAnaliseProfissionais.getModel();

        modelo.setRowCount(0);

        while (rs.next()) {
            modelo.addRow(new Object[]{
                rs.getInt("id_usuario"),
                rs.getString("nome"),
                rs.getString("email"),
                rs.getString("whatsapp"),
                rs.getString("descricao"),
                rs.getString("cidade"),
                rs.getString("status_cadastro"),
                rs.getTimestamp("data_cadastro")
            });
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Erro ao carregar profissionais: " + e.getMessage()
        );
    }
} // MÉTODO PARA IXIBINDO AS IMAGENS NO JLAB PRO RG 
    private void exibirImagem(String caminho, javax.swing.JLabel label) {

    // Verifica se existe um caminho para a imagem.
    if (caminho == null || caminho.trim().isEmpty()) {
        label.setIcon(null);
        label.setText("Documento não enviado");
        return;
    }

    try {

        // Endereço do servidor onde estão armazenadas as imagens.
        String enderecoServidor =
                "http://192.168.0.73/montemax/";

        // Monta o endereço completo da imagem.
        java.net.URL url = new java.net.URL(
                enderecoServidor + caminho
        );

        // Carrega a imagem através do servidor.
        javax.swing.ImageIcon imagem =
                new javax.swing.ImageIcon(url);

        // Verifica se a imagem foi carregada corretamente.
        if (imagem.getIconWidth() <= 0) {
            label.setIcon(null);
            label.setText("Não foi possível carregar a imagem");
            return;
        }

        // Redimensiona a imagem para caber no JLabel.
        java.awt.Image imagemRedimensionada =
                imagem.getImage().getScaledInstance(
                        250,
                        180,
                        java.awt.Image.SCALE_SMOOTH
                );

        // Exibe a imagem na tela.
        label.setText("");
        label.setIcon(
                new javax.swing.ImageIcon(imagemRedimensionada)
        );

    } catch (java.net.MalformedURLException e) {

        label.setIcon(null);
        label.setText("Endereço da imagem inválido");

        System.out.println("Erro na URL: " + e.getMessage());

    }
}


