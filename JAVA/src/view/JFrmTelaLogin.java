    private void jBtnEntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnEntrarActionPerformed
    
            
String email = jTxtUsuario.getText().trim();
String senha = new String(jPswSenha.getPassword());

if (email.isEmpty() || senha.isEmpty()) {
    JOptionPane.showMessageDialog(
        this,
        "Informe o e-mail e a senha."
    );
    return;
}

String sql =
    "SELECT u.senha " +
    "FROM usuario u " +
    "INNER JOIN administrador a " +
    "ON a.id_usuario = u.id_usuario " +
    "WHERE u.email = ? " +
    "AND u.tipo_usuario = 'ADMIN' " +
    "AND u.status_conta = 'ATIVO'";

try (
    Connection conexao = Conexao.abrirConexao();
    PreparedStatement stmt = conexao.prepareStatement(sql)
) {
    stmt.setString(1, email);

    try (ResultSet resultado = stmt.executeQuery()) {

        if (resultado.next()) {
            String hashBanco = resultado.getString("senha");

            if (BCrypt.checkpw(senha, hashBanco)) {
                JOptionPane.showMessageDialog(
                    this,
                    "Login realizado com sucesso!"
                );

               
                if (BCrypt.checkpw(senha, hashBanco)) {

    JFrmTelaPrincipal telaPrincipal =
            new JFrmTelaPrincipal();

    telaPrincipal.setLocationRelativeTo(null);
    telaPrincipal.setVisible(true);

    this.dispose();
}
            } else {
                JOptionPane.showMessageDialog(
                    this,
                    "E-mail ou senha incorretos."
                );
            }

        } else {
            JOptionPane.showMessageDialog(
                this,
                "E-mail ou senha incorretos, ou conta sem acesso administrativo."
            );
        }
    }

} catch (SQLException e) {
    JOptionPane.showMessageDialog(
        this,
        "Erro ao consultar o banco de dados: " + e.getMessage()
    );
}

    }//GEN-LAST:event_jBtnEntrarActionPerformed

