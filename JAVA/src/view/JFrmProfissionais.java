    private void carregarProfissionais(String pesquisa) {
        
//busca somente os usuários do tipo usuario, sem misturar os profissionais e administradores.
    modelo = new DefaultTableModel();

    modelo.addColumn("ID"); // adicionando as colunas pra aparecer na tabela 
    modelo.addColumn("Nome");
    modelo.addColumn("E-mail");
    modelo.addColumn("Situação");

    String sql = "SELECT u.id_usuario, u.nome, u.email, p.status_cadastro, "
        + "p.whatsapp, p.descricao, p.cidade, p.data_cadastro "
        + "FROM usuario u "
        + "INNER JOIN profissional p "
        + "ON u.id_usuario = p.id_usuario "
        + "WHERE u.tipo_usuario = 'profissional' "
        + "AND (CAST(u.id_usuario AS CHAR) LIKE ? "
        + "OR u.nome LIKE ? "
        + "OR u.email LIKE ?) "
        + "ORDER BY u.id_usuario DESC";
 
    try (Connection conn = Conexao.abrirConexao();
         PreparedStatement stmt = conn.prepareStatement(sql)) {

        String filtro = "%" + pesquisa + "%"; //pesquisar sobre isso 

        stmt.setString(1, filtro);
        stmt.setString(2, filtro);
        stmt.setString(3, filtro);

        try (ResultSet rs = stmt.executeQuery()) {

            while (rs.next()) {
                modelo.addRow(new Object[]{
                    rs.getInt("id_usuario"),
                    rs.getString("nome"),
                    rs.getString("email"),
                    rs.getString("status_cadastro")
                });
            }
        }

        jTbProfissionais.setModel(modelo);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "Erro ao pesquisar profissionais : " + e.getMessage());
    
       }
}
    
    
